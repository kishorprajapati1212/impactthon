import { describe, it, expect } from "vitest";
import { render, screen } from "@testing-library/react";
import "@testing-library/jest-dom/vitest";
import fs from "node:fs";
import path from "node:path";
import BrandMark from "../components/Brand/BrandMark.jsx";
import BrandLogo from "../components/Brand/BrandLogo.jsx";
import { BRAND } from "../brand.js";

const FRONTEND = path.resolve(__dirname, "../..");
const PUBLIC = path.join(FRONTEND, "public");
const read = (p) => fs.readFileSync(p, "utf8");
const pngSize = (p) => {
  const b = fs.readFileSync(p);
  expect(b.subarray(1, 4).toString()).toBe("PNG");
  return { width: b.readUInt32BE(16), height: b.readUInt32BE(20) };
};

/**
 * The logo is the Instagram identity (profile picture / reels / carousels):
 * QR-viewfinder mark with an indigo scan-line + "AttendX" wordmark whose "X"
 * carries the brand accent, tagline "Attendance, made simple."
 */
describe("Brand components", () => {
  it("BrandMark is an accessible SVG with the viewfinder frame and the scan-line", () => {
    const { container } = render(<BrandMark size={40} />);
    const svg = screen.getByRole("img", { name: "AttendX logo" });
    expect(svg.getAttribute("viewBox")).toBe("0 0 96 96");
    expect(svg.getAttribute("width")).toBe("40");
    // 4 frame strokes (currentColor) + 1 rounded scan-line in brand colours
    expect(container.querySelectorAll('g[fill="currentColor"] rect')).toHaveLength(4);
    const line = container.querySelector("rect[rx]");
    expect(line.getAttribute("width")).toBe("34");
    expect(line.getAttribute("class")).toContain("fill-brand-blue");
    expect(line.getAttribute("class")).toContain("dark:fill-brand-indigo");
  });

  it("tile tone is the app icon: navy rounded tile, white frame, indigo line", () => {
    const { container } = render(<BrandMark tone="tile" size={36} />);
    const tile = container.querySelector("rect[rx='22']");
    expect(tile.getAttribute("fill")).toBe(BRAND.colors.navy);
    expect(container.querySelector('g[fill="#ffffff"]')).toBeTruthy();
    expect(container.querySelector("rect[rx='3.5']").getAttribute("fill")).toBe(BRAND.colors.indigo);
  });

  it("BrandLogo renders mark + wordmark; the X carries the brand accent", () => {
    const { container } = render(<BrandLogo size="md" />);
    expect(screen.getByRole("img", { name: "AttendX logo" })).toBeTruthy();
    expect(container).toHaveTextContent("AttendX");
    const x = container.querySelector("span.text-brand-blue");
    expect(x).toHaveTextContent("X");
    expect(container.textContent).not.toContain(BRAND.tagline); // tagline is opt-in
  });

  it("stacked lock-up with tagline uses the requested heading element (login page h1)", () => {
    const { container } = render(<BrandLogo as="h1" size="lg" stacked tagline />);
    expect(screen.getByRole("heading", { level: 1 })).toHaveTextContent("AttendX");
    expect(container).toHaveTextContent("Attendance, made simple.");
  });

  it("brand constants: Instagram colours + tagline; social links hidden until set", () => {
    expect(BRAND.colors).toMatchObject({ navy: "#11172f", indigo: "#5a65f1", blue: "#0b4ff8" });
    expect(BRAND.tagline).toBe("Attendance, made simple.");
    expect(typeof BRAND.social.instagram).toBe("string");
  });
});

describe("Brand static assets (generated by scripts/brand-assets.py)", () => {
  it("favicon, app icons, manifest and OG image exist with the right sizes", () => {
    for (const f of ["favicon.ico", "favicon.svg", "apple-touch-icon.png", "icon-192.png", "icon-512.png", "icon-maskable-512.png", "site.webmanifest", "og-image.png"]) {
      expect(fs.existsSync(path.join(PUBLIC, f)), f).toBe(true);
    }
    expect(pngSize(path.join(PUBLIC, "icon-192.png"))).toEqual({ width: 192, height: 192 });
    expect(pngSize(path.join(PUBLIC, "icon-512.png"))).toEqual({ width: 512, height: 512 });
    expect(pngSize(path.join(PUBLIC, "icon-maskable-512.png"))).toEqual({ width: 512, height: 512 });
    expect(pngSize(path.join(PUBLIC, "apple-touch-icon.png"))).toEqual({ width: 180, height: 180 });
    expect(pngSize(path.join(PUBLIC, "og-image.png"))).toEqual({ width: 1200, height: 630 });
    expect(read(path.join(PUBLIC, "favicon.svg"))).toContain(`fill="${BRAND.colors.navy}"`);
  });

  it("web manifest is valid and every icon it lists is shipped", () => {
    const m = JSON.parse(read(path.join(PUBLIC, "site.webmanifest")));
    expect(m.short_name).toBe("AttendX");
    expect(m.theme_color).toBe(BRAND.colors.navy);
    expect(m.icons.some((i) => i.purpose === "maskable")).toBe(true);
    for (const icon of m.icons) expect(fs.existsSync(path.join(PUBLIC, icon.src.replace(/^\//, ""))), icon.src).toBe(true);
  });

  it("index.html links the icons/manifest and the Organization logo points at a real 512px image", () => {
    const html = read(path.join(FRONTEND, "index.html"));
    expect(html).toMatch(/<link rel="icon" href="\/favicon\.svg" type="image\/svg\+xml" \/>/);
    expect(html).toMatch(/<link rel="icon" href="\/favicon\.ico"/);
    expect(html).toMatch(/<link rel="apple-touch-icon" href="\/apple-touch-icon\.png" \/>/);
    expect(html).toMatch(/<link rel="manifest" href="\/site\.webmanifest" \/>/);
    expect(html).toContain(`<meta name="theme-color" content="${BRAND.colors.navy}" />`);
    const blocks = [...html.matchAll(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/g)]
      .map((m) => JSON.parse(m[1].replace(/__SITE_URL__/g, "https://example.edu")));
    const graph = blocks.find((b) => Array.isArray(b["@graph"]));
    expect(graph).toBeTruthy();
    const org = graph["@graph"].find((n) => n["@type"] === "Organization");
    expect(org.logo).toMatchObject({ "@type": "ImageObject", url: "https://example.edu/icon-512.png", width: 512, height: 512 });
    expect(org.slogan).toBe(BRAND.tagline);
  });
});
